const generateHistory = (baseVal: number, variance: number): { time: string; value: number }[] => {
  const times = ['00:00', '03:00', '06:00', '09:00', '12:00', '15:00', '18:00', '21:00', 'Сейчас'];
  return times.map((time, idx) => {
    const offset = Math.sin(idx * 0.8) * variance + (Math.random() * (variance * 0.4) - variance * 0.2);
    return {
      time,
      value: Number((baseVal + offset).toFixed(1)),
    };
  });
};

